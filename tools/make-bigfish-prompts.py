def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--batch', type=int, action='append', help='只出这批（可重复）')
    ap.add_argument('--out', default=str(OUT_DEFAULT))
    args = ap.parse_args()

    style = json.loads(STYLE_JSON.read_text())
    lock = style['styleLock']
    bg = style['background']

    frames = FRAMES if not args.batch else [f for f in FRAMES if f[1] in args.batch]

    lines = []
    A = lines.append
    A('# Q版大肥鱼 · 生图提示词清单')
    A('')
    A('> **这份是「可以直接复制粘贴」的** —— 每一帧一个代码框，')
    A('> 里面是**已经拼好**的完整提示词（动作 + 风格锁 + 绿幕）。')
    A('>')
    A('> ⚠️ **每次生成还要做两件事，光复制提示词不够**：')
    A('> 1. **附上参考图**（见下面的清单）')
    A('> 2. **尺寸选 512×512**')
    A('')
    A('---')
    A('')
    A('## ⚠️ 每次都要附的参考图')
    A('')
    A('路径：`pet-art/big-fish/refs/`')
    A('')
    A('| 文件 | 什么时候附 |')
    A('|---|---|')
    A('| **`01-立绘定稿.png`** | **每次都附**（整体长相）|')
    A('| **`10-站姿成品（发箍基准）.png`** | **每次都附**（发箍画法的基准）⭐ |')
    A('| `05-眼睛特写.png` | 有闭眼 / 眯眼 / 瞪眼的帧 |')
    A('| `09-闭眼特写.png` | **闭眼的那几帧必附**（呼吸眨眼 / 打字眨眼）|')
    A('| `06-发箍蝴蝶结.png` | 头在动的帧（东张西望 / 被吓到）|')
    A('| `07-鲸鱼鳍耳朵.png` | 耳朵相位不是 0 的帧 |')
    A('| `02-正视图.png` `03-左侧面.png` `04-背视图.png` | 头转向侧面的帧（东张西望）|')
    A('')
    A('> ⚠️ **同一次不要超过 10 张参考图** —— 接口会报')
    A('> `InvalidParameter: number of reference images cannot exceed 10`。')
    A('')
    A('---')
    A('')
    A('## 通用规格（每张都一样）')
    A('')
    A('| 项 | 值 |')
    A('|---|---|')
    A('| **画布** | **512 × 512** |')
    A('| **背景** | **纯绿幕 `#00FF00`**（提示词里已经写了）|')
    A('| **站位** | **正面站立、脚底对齐同一基线、水平居中** |')
    A('| **入镜** | **整个身体完整入镜，任何部位不得被裁切** |')
    A('')

    # 分批输出
    BATCH_NAME = {
        1: '第 1 批 · 四个「只有 1 张」的状态（最急）',
        2: '第 2 批 · 待机链（最常看到）',
        3: '第 3 批 · 工作与完成',
        4: '第 4 批 · 短动作',
    }
    cur = None
    for lg, batch, usage, prompt in frames:
        if batch != cur:
            cur = batch
            A('')
            A('---')
            A('')
            A(f'## {BATCH_NAME[batch]}')
            A('')
        # ⚠️ 全局约束插在**动作后面、风格锁前面** ——
        #    动作说"做什么"，约束说"边界在哪"，最后才是长相。
        parts = [prompt, LOCAL_ONLY, HAIR_LOCK, APPENDAGE_RULE, NO_OCCLUSION]
        if '脸颊' in prompt or '鼓' in prompt:
            parts.append(CHEEK_RULE)
        parts += [lock, bg]
        full = ' '.join(parts)
        A(f'### `{lg}` · {usage}')
        A('')
        A('```text')
        A(full)
        A('```')
        A('')

    A('---')
    A('')
    A(f'**共 {len(frames)} 帧。**')
    A('')

    out = pathlib.Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text('\n'.join(lines))
    print(f'  ✅ {out}')
    print(f'     {len(frames)} 帧，每帧提示词约 {len(frames[0][3]) + len(lock) + len(bg)} 字')
    print(f'     文件 {out.stat().st_size / 1024:.0f} KB')


if __name__ == '__main__':
    main()
